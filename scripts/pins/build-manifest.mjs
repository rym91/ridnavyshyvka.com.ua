const LIMITS = { title: 100, description: 500, alt: 500 };

function build() {
  const pins = [];
  const warnings = [];
  const seen = new Set();

  for (const page of PAGES) {
    const section = SECTIONS[page.section];
    if (!section) throw new Error(`Невідомий розділ: ${page.section} (${page.slug})`);

    const photoPath = path.join('src/assets/heroes', page.photo);
    if (!fs.existsSync(path.join(ROOT, photoPath))) {
      throw new Error(`Немає фото ${photoPath} для ${page.slug}`);
    }

    for (const v of page.variants) {
      const id = `${page.slug}_${v.v}`;
      if (seen.has(id)) throw new Error(`Дубль піна: ${id}`);
      seen.add(id);

      const pin = {
        id,
        slug: page.slug,
        variant: v.v,
        layout: v.layout,
        section: page.section,
        board: section.board,
        eyebrow: v.eyebrow ?? section.eyebrow,
        photo: photoPath,
        focus: v.focus ?? '50% 50%',
        zoom: v.zoom ?? 1,
        pan: v.pan ?? '0% 0%',
        headline: v.headline,
        hook: v.hook ?? '',
        link: SITE + page.url,
        image_url: `${SITE}/pins/pin_${id}.jpg`,
        title: v.title,
        description: v.desc,
        alt_text: v.alt ?? page.alt,
        keywords: v.keywords ?? page.keywords,
      };

      for (const [field, max] of Object.entries(LIMITS)) {
        const key = field === 'alt' ? 'alt_text' : field;
        if ((pin[key] || '').length > max) {
          warnings.push(`${id}: ${key} — ${pin[key].length} символів (ліміт ${max})`);
        }
      }
      if (fs.existsSync(path.join(ROOT, 'public/pins', `pin_${id}.jpg`))) {
        warnings.push(`${id}: файл уже є в public/pins — буде перезаписано`);
      }
      pins.push(pin);
    }
  }

  const out = { generated: new Date().toISOString().slice(0, 10), count: pins.length, pins };
  fs.writeFileSync(path.join(ROOT, 'scripts/pins/pins.json'), JSON.stringify(out, null, 2) + '\n');

  const byLayout = pins.reduce((a, p) => ((a[p.layout] = (a[p.layout] || 0) + 1), a), {});
  console.log(`Пінів у маніфесті: ${pins.length}`);
  console.log('Розкладки:', Object.entries(byLayout).map(([k, n]) => `${k}=${n}`).join(', '));
  console.log(`URL-адрес: ${new Set(pins.map((p) => p.link)).size}`);
  if (warnings.length) {
    console.log('\nПопередження:');
    for (const w of warnings) console.log('  ·', w);
  }
}

build();
