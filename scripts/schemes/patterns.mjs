/**
 * Восьмипроменева зірка складається з трьох частин, і кожна задана в тій
 * метриці, в якій вона природно лягає на клітинку:
 *
 *   тіло       — ромб у манхеттенській метриці (|x|+|y| ≤ M);
 *   4 промені  — прямі бруси завширшки 2A+1 з вістрям під 45° (крок 1:1);
 *   4 промені  — діагональні бруси тієї ж ширини, зрізані по анти-діагоналі.
 *
 * Обʼєднання ромба з квадратом («зірка Лакшмі») тут не годиться: у нього
 * западини сидять на радіусі 1.08·S при вістрях на 1.41·S, тобто r/R ≈ 0.77 —
 * око бачить восьмикутник, а не зірку. Тут r/R ≈ 0.43: зірка читається як
 * зірка. Ширину променів навмисне тримаємо на 5 клітинках — вужчі промені
 * вироджуються у «вусики» по одному стібку, ширші заливають западини.
 */
const GEO = { M: 7, A: 2, R: 15, Dw: 2, Dt: 20, size: 31 };

const body = (ax, ay) => ax + ay <= GEO.M;

const arms = (ax, ay) =>
  (ax <= GEO.R && ay <= Math.min(GEO.A, GEO.R - ax)) ||
  (ay <= GEO.R && ax <= Math.min(GEO.A, GEO.R - ay));

const rays = (ax, ay) => {
  const along = ax + ay;
  const across = Math.abs(ax - ay);
  return along <= GEO.Dt && across <= Math.min(GEO.Dw, GEO.Dt - along);
};

/**
 * Кольори розкладені не обводкою, а по частинах мотиву: чорний ромб у центрі,
 * червоні прямі промені з чорними вістрями, чорні діагональні промені.
 *
 * Сенс саме в чергуванні. Якщо просто залити прямий хрест червоним, а
 * діагоналі чорним, чорне читається як чотири окремі клини поруч із червоним
 * прицілом — два кольори не тримаються купи. Коли чорне з’являється і в
 * центрі, і на діагоналях, і на вістрях, воно замикає мотив у цілу розетку.
 *
 * Друга причина суто практична: великі суцільні поля одного кольору — це
 * менше перезаправок голки, ніж обведення кожного контуру. Так вишивають
 * насправді.
 */
const TIP = 13; // від якої відстані вістря прямого променя стає чорним
const CORE = 3; // радіус чорного ромба в центрі (манхеттенський)

function starGrid() {
  const c = (GEO.size - 1) / 2;
  const grid = [];
  for (let y = 0; y < GEO.size; y++) {
    let row = '';
    for (let x = 0; x < GEO.size; x++) {
      const ax = Math.abs(x - c);
      const ay = Math.abs(y - c);
      const onBody = body(ax, ay);
      const onArm = arms(ax, ay);
      if (!onBody && !onArm && !rays(ax, ay)) {
        row += '.';
        continue;
      }
      const black =
        !onBody && !onArm ||                          // діагональний промінь
        (onArm && !onBody && Math.max(ax, ay) >= TIP) || // вістря прямого променя
        ax + ay <= CORE;                              // ромб у центрі
      row += black ? 'k' : 'r';
    }
    grid.push(row);
  }
  return grid;
}

