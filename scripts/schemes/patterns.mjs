/**
 * Схеми для вишивки хрестиком — джерело правди.
 *
 * Сітка задається правилом, а не вручну по клітинці: так у мотиві не буває
 * «конфеті» (поодиноких стібків, через які схему ненавидять вишивальниці),
 * симетрія виходить точною, і мотив легко перерахувати під інший розмір.
 *
 * Символи: 'r' — червоний, 'k' — чорний, '.' — полотно без вишивки.
 */

