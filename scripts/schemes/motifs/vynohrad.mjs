/**
 * Виноградне гроно.
 *
 * Мотив зібраний із частин, а не намальований цілком: ягода — один штамп,
 * покладений у чотири ряди, лист і прожилки — два малюнки. Так гроно можна
 * перебудувати (додати ряд, зсунути), не перемальовуючи ягоди по клітинці.
 *
 * Ягода 5×5 зі зрізаними кутами. Ширина непарна навмисне: у ягоди з парною
 * шириною центр припадає на межу клітинок, і ряди по 2 та по 3 ягоди вже не
 * вирівняти по одній осі — гроно з'їжджає набік на пів клітинки.
 *
 * Ряди йдуть 2-3-2-1 і торкаються по вертикалі. Ряди 3-2-3-2-1 однакової
 * ширини давали прямокутник: гроно читається гроном, лише коли звужується.
 */
import { blank, art, stamp } from '../lib.mjs';

const BERRY = art(`
.rrr.
rrrrr
rrrrr
rrrrr
.rrr.
`);

const LEAF = art(`
...kk...kk...
..kkkk.kkkk..
.kkkkkkkkkkk.
kkkkkkkkkkkkk
kkkkkkkkkkkkk
.kkkkkkkkkkk.
..kkkkkkkkk..
...kkkkkkk...
....kkkkk....
.....kkk.....
`);

/**
 * Прожилки поверх листка. Одна центральна й одна пара бічних — не більше:
 * перший варіант мав три пари, і на канві вони склалися не у прожилки, а в
 * решітку, крізь яку сам листок уже не читався.
 */
const VEINS = art(`
.............
.............
......r......
...r..r..r...
....r.r.r....
.....rrr.....
......r......
......r......
......r......
......r......
`);

const BUNCH = [[13, [3, 9]], [18, [0, 6, 12]], [23, [3, 9]], [28, [6]]];

let g = blank(17, 33);
g = stamp(g, LEAF, 2, 0);
g = stamp(g, VEINS, 2, 0);
g = stamp(g, art('k\nk\nk'), 8, 10); // стебло від листка до грона
for (const [y, xs] of BUNCH) for (const x of xs) g = stamp(g, BERRY, x, y);

export default {
  id: 'vynohradne-hrono',
  title: 'Виноградне гроно',
  subtitle: 'Класичний мотив весільних і святкових рушників',
  grid: g,
  level: 'Середній',
  hours: '4–5 годин',
  strands: '2 складання на аїді 14 і 16, 1–2 складання на аїді 18',
  needle: 'гобеленова №24 (аїда 14 і 16), №26 (аїда 18)',
  meaning:
    'Виноград — один із найчастіших рослинних мотивів на українських рушниках, надто весільних. Його читають як знак достатку й родини, але саме таке тлумачення записане вже в літературі XX століття; давніші джерела значень не фіксують. Певне інше: виноград прийшов у народну вишивку з церковного мистецтва, де він був давно й повсюдно.',
  dating:
    'Рослинні мотиви на рушниках — пізніший шар, ніж геометричні: вони поширюються з XVIII–XIX століть, разом із міськими та церковними зразками. Червоно-чорна гама, у якій ми подаємо гроно, ще пізніша — кінець XIX століття.',
};
