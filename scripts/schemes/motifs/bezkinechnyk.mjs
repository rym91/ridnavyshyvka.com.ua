  subtitle: 'Бордюр для рушника, манжета або низу сорочки',
  grid,
  rapport: RAPPORT,
  level: 'Початковий',
  hours: '4–5 годин на 30 см',
  strands: '2 складання на аїді 14 і 16, 1–2 складання на аїді 18',
  needle: 'гобеленова №24 (аїда 14 і 16), №26 (аїда 18)',
