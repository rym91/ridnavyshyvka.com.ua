/**
 * Безкінечник (меандр) — бордюр.
 *
 * Тут принципово інша техніка побудови, ніж у розеток. Безкінечник — це одна
 * лінія, і намальована руками по клітинці вона рветься саме там, куди не
 * дивишся. Тому лінію задаємо ламаною і обводимо: розрив тоді просто
 * неможливий, а ширину каналів між витками видно з координат.
 *
 * Раппорт 12 хрестиків. Показуємо три — менше не дає побачити повтор, більше
 * не влазить у смугу набору без дрібної клітинки.
 */
import { blank, stroke, tile } from '../lib.mjs';

const RAPPORT = 12;
const REPEATS = 3;

/**
 * Один виток. Спіраль звисає з нижньої напрямної, і саме напрямна зшиває
 * витки в нескінченну лінію — прибрати її означає розсипати бордюр на
 * окремі завитки й втратити те, від чого мотив назвали безкінечником.
 *
 * Вістря спіралі закінчуємо на 5, а не на 6: при товщині 2 воно інакше
 * дістає до правої стійки, канал замикається і замість спіралі виходить
 * глухий прямокутник.
 */
function coil() {
  let g = blank(RAPPORT, 13);
  g = stroke(g, [[0, 11], [0, 0]], 'r', 2); // ліва стійка вгору
  g = stroke(g, [[0, 0], [8, 0]], 'r', 2); // верхня полиця
  g = stroke(g, [[8, 0], [8, 8]], 'r', 2); // права стійка вниз
  g = stroke(g, [[8, 8], [4, 8]], 'r', 2); // поворот усередину
  g = stroke(g, [[4, 8], [4, 4]], 'r', 2); // вгору до серцевини
  g = stroke(g, [[4, 4], [5, 4]], 'r', 2); // вістря спіралі
  g = stroke(g, [[0, 11], [11, 11]], 'r', 2); // нижня напрямна
  g = stroke(g, [[6, 6], [6, 6]], 'k', 2); // око спіралі
  return g;
}

const band = tile(coil(), REPEATS);
const W = band[0].length;
const rail = ['k'.repeat(W), 'k'.repeat(W)];
const gap = '.'.repeat(W);

/**
 * Рейки зверху й знизу — не прикраса, а те, що робить із мотиву бордюр:
 * вони дають лінію, по якій його рівно кладуть на рушник чи манжет.
 * Порожній рядок між рейкою й меандром обовʼязковий: впритул рейка зливається
 * з полицею спіралі в суцільну чотирирядну колоду.
 */
const grid = [...rail, gap, ...band, gap, ...rail];

