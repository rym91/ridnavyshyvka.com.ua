/**
 * Ромб із гачками.
 *
 * Концентричні ромби задані правилом — це чиста манхеттенська геометрія, і
 * будь-яка спроба намалювати їх руками дасть лише шанс схибити на клітинку.
 * А от гачок на вершині правилом не задається: це десяток конкретних рішень,
 * тож він виписаний окремо, координатами.
 *
 * Кольори чергуються від краю до центру — червоний, чорний, червоний. Форму
 * тримає червоне: воно й малює силует ромба з гачками, а чорне кільце всередині
 * працює як тінь. У зворотному розкладі чорне забирало дві третини стібків, і
 * ромб читався важким, а червоного в «червоно-чорній» схемі майже не було видно.
 */
import { symmetric } from '../lib.mjs';

const SIZE = 27; // центр на 13, отже максимальна манхеттенська відстань по осі — 13

const ring = (d, from, to) => d >= from && d <= to;

/**
 * Гачок-тризубець на вершині ромба: стебло вгору від вістря, поперечка і три
 * ріжки. Записуємо одну орієнтацію (a — впоперек, b — уздовж осі) і додаємо
 * ту саму формулу з переставленими осями — так усі чотири гачки однакові за
 * побудовою, а не за уважністю.
 */
const prong = (a, b) =>
  (b === 13 && (a === 0 || a === 2)) || // три ріжки
  (b === 12 && a <= 2) ||               // поперечка
  (b === 11 && a === 0);                // стебло

const grid = symmetric(SIZE, (ax, ay) => {
  const d = ax + ay;
  if (prong(ax, ay) || prong(ay, ax)) return 'r';
  if (ring(d, 9, 10)) return 'r';
  if (ring(d, 5, 7)) return 'k';
  if (d <= 3) return 'r';
  return '.';
});

