/**
 * Вазон (дерево життя) — центральна композиція рушника й найбільший мотив набору.
 *
 * Зібраний із деталей: квітка-вінець, чотири тюльпани, листки, вазон і стебла.
 * Малювати таке цілком по клітинці немає сенсу — дві половини однаково
 * розійдуться, а тут симетрія лівого й правого боку задана тим, що деталь
 * ставиться двічі на дзеркальні координати.
 *
 * Гілки йдуть сходинками, а не прямою. Перший варіант мав прямі горизонтальні
 * гілки — через увесь мотив ішла поперечина, і рослини в ній не було видно.
 */
import { blank, art, stamp, mirrorX, flipX, stroke, branch } from '../lib.mjs';

/** Квітка-вінець: три пелюстки, чашечка, стебло. */
const CROWN = art(`
rrr...r...rrr
rrrr.rrr.rrrr
rrrrrrrrrrrrr
rrrrrrrrrrrrr
rrrrrrrrrrrrr
.rrrrrrrrrrr.
..rrrrrrrrr..
...rrrrrrr...
....rrrrr....
.....kkk.....
......k......
......k......
`);

/** Бічна квітка — той самий силует, менший. Стебло знизу сідає на гілку. */
const TULIP = art(`
rr..r..rr
rrr.r.rrr
rrrrrrrrr
rrrrrrrrr
.rrrrrrr.
..rrrrr..
...kkk...
....k....
....k....
`);

/** Листок при стеблі. Правий — те саме дзеркально, щоб вістря дивилися нарізно. */
const LEAF_L = art(`
..rr.
.rrrr
rrrr.
.rr..
`);
const LEAF_R = flipX(LEAF_L);

/** Вазон. Малюємо половину: у горщика вісь одна, і на око її не витримати. */
const VASE = mirrorX(art(`
kkkkkkkk
kkkkkkkk
.rrrrrrr
.rrrrrrr
..rrrrrr
...rrrrr
....rrrr
.....kkk
...kkkkk
..kkkkkk
`));

const AXIS = 17;

let g = blank(35, 51);
g = stamp(g, CROWN, AXIS - 6, 0);
g = stroke(g, [[AXIS, 12], [AXIS, 39]], 'k'); // центральне стебло
g = branch(g, [AXIS, 26], [9, 22], 'k');
g = branch(g, [AXIS, 26], [25, 22], 'k');
g = branch(g, [AXIS, 37], [7, 33], 'k');
g = branch(g, [AXIS, 37], [27, 33], 'k');
g = stamp(g, TULIP, 5, 14);
g = stamp(g, TULIP, 21, 14);
g = stamp(g, TULIP, 3, 25);
g = stamp(g, TULIP, 23, 25);
// Листки лише на нижньому ярусі. Угорі між стеблом і квіткою лишається три
// стовпці — листок туди або злипається з квіткою, або затирає саме стебло.
// Нижче квіти розходяться ширше, і місце для листка з'являється.
g = stamp(g, LEAF_L, 12, 29);
g = stamp(g, LEAF_R, 18, 29);
g = stamp(g, VASE, 10, 39);

export default {
  id: 'vazon-derevo-zhyttia',
  title: 'Вазон (дерево життя)',
  subtitle: 'Центральна композиція весільного рушника',
  grid: g,
  level: 'Середній',
  hours: '6–8 годин',
  strands: '2 складання на аїді 14 і 16, 1–2 складання на аїді 18',
  needle: 'гобеленова №24 (аїда 14 і 16), №26 (аїда 18)',
  meaning:
    'Вазон — це рослина, що росте з горщика: стебло, симетричні гілки з квітами й квітка-вінець угорі. Так називали композицію самі вишивальниці; «дерево життя» — назва пізніша, дослідницька. Вазон вишивали передусім на весільних рушниках, і це та частина рушника, за якою впізнають регіон.',
  dating:
    'Вазон на рушниках склався у XVIII–XIX століттях під впливом міських і церковних зразків. Червоно-чорна гама тут — кінець XIX століття; давніші вазони бували значно барвистішими, і однією червоною з чорною їх не обмежували.',
};
