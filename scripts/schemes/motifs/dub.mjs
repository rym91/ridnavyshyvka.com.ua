/**
 * Дубове листя з жолудями.
 *
 * Листок намальований половиною й віддзеркалений: у дуба лопаті мають стояти
 * рівно навпроти одна одної, а намальовані окремо праворуч і ліворуч вони
 * розходяться на клітинку — і листок починає виглядати пожованим.
 *
 * Виїмки між лопатями глибокі навмисне. Дрібні виїмки дають просто листок,
 * а дуб упізнають саме по глибині лопатей.
 */
import { blank, art, stamp, mirrorX, stroke } from '../lib.mjs';

/** Ліва половина листка; права колонка — вісь, при дзеркаленні не подвоюється. */
const HALF = art(`
.....rr
...rrrr
..rrrrr
..rrrrr
...rrrr
.....rr
..rrrrr
rrrrrrr
rrrrrrr
.rrrrrr
....rrr
.rrrrrr
rrrrrrr
.rrrrrr
...rrrr
.....rr
......r
......r
......r
`);

/** Жолудь: шапочка чорна, ядро червоне. Пропорція приблизно 1 до 3. */
const ACORN = art(`
.kkkkk.
kkkkkkk
.rrrrr.
.rrrrr.
.rrrrr.
.rrrrr.
..rrr..
...r...
`);

const LEAF = mirrorX(HALF);
const W = 23;

let g = blank(W, 30);
g = stamp(g, LEAF, 5, 0);
g = stroke(g, [[11, 2], [11, 20]], 'k'); // центральна жилка переходить у стебло
g = stroke(g, [[5, 20], [17, 20]], 'k'); // гілка до жолудів
g = stamp(g, ACORN, 2, 21);
g = stamp(g, ACORN, 14, 21);

export default {
  id: 'dubove-lystia-z-zholudiamy',
  title: 'Дубове листя з жолудями',
  subtitle: 'Мотив чоловічих сорочок і рушників',
  grid: g,
  level: 'Середній',
  hours: '4–5 годин',
  strands: '2 складання на аїді 14 і 16, 1–2 складання на аїді 18',
  needle: 'гобеленова №24 (аїда 14 і 16), №26 (аїда 18)',
  meaning:
    'Дуб і жолуді вишивали переважно на чоловічих сорочках. Тлумачення «сила, міць, чоловіча стать» ходить у популярній літературі; воно виглядає природним, але записане пізно — етнографи XIX століття значень від самих вишивальниць не фіксували. Що справді відомо: розподіл мотиву за статтю власника одягу.',
  dating:
    'Рослинні мотиви на сорочках поширюються з XVIII–XIX століть. Червоно-чорна гама — ще пізніша: кінець XIX століття, разом із фабричною заполоччю.',
};
